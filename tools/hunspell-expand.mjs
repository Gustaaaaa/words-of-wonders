// Minimal Hunspell affix expander (suffixes, prefixes, cross-product and one
// level of continuation classes). Good enough to enumerate every inflected
// form of a dictionary such as VERO (pt-BR) so the game can validate words.
import { readFileSync } from 'node:fs';

function parseAff(text) {
  const rules = new Map(); // flag -> {type, cross, entries:[{strip, add, contFlags, cond}]}
  let forbidden = null;
  let noSuggest = null;
  const lines = text.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].replace(/\s+#.*$/, '');
    const parts = line.trim().split(/\s+/);
    if (parts[0] === 'FORBIDDENWORD') forbidden = parts[1];
    if (parts[0] === 'NOSUGGEST') noSuggest = parts[1];
    if ((parts[0] === 'SFX' || parts[0] === 'PFX') && parts.length === 4 && /^\d+$/.test(parts[3])) {
      const [type, flag, cross, countStr] = parts;
      const count = Number(countStr);
      const entries = [];
      for (let j = 1; j <= count; j++) {
        const p = lines[i + j].trim().split(/\s+/);
        let [, , strip, add, cond = '.'] = p;
        let contFlags = '';
        if (add.includes('/')) [add, contFlags] = add.split('/');
        if (strip === '0') strip = '';
        if (add === '0') add = '';
        const re = type === 'SFX' ? new RegExp(cond + '$', 'u') : new RegExp('^' + cond, 'u');
        entries.push({ strip, add, contFlags: [...contFlags], cond: re });
      }
      rules.set(flag, { type, cross: cross === 'Y', entries });
      i += count;
    }
  }
  return { rules, forbidden, noSuggest };
}

function applySfx(word, rule) {
  const out = [];
  for (const e of rule.entries) {
    if (!e.cond.test(word)) continue;
    if (e.strip && !word.endsWith(e.strip)) continue;
    out.push({ word: word.slice(0, word.length - e.strip.length) + e.add, cont: e.contFlags });
  }
  return out;
}

function applyPfx(word, rule) {
  const out = [];
  for (const e of rule.entries) {
    if (!e.cond.test(word)) continue;
    if (e.strip && !word.startsWith(e.strip)) continue;
    out.push({ word: e.add + word.slice(e.strip.length), cont: e.contFlags });
  }
  return out;
}

/**
 * Calls onWord(word, {stem, flags, noSuggest}) for every form generated by the dictionary.
 */
export function expandHunspell(dicPath, affPath, onWord) {
  const { rules, forbidden, noSuggest } = parseAff(readFileSync(affPath, 'utf8'));
  const dic = readFileSync(dicPath, 'utf8').split(/\r?\n/).slice(1);
  for (const raw of dic) {
    if (!raw) continue;
    const line = raw.split(/\s/)[0];
    const slash = line.indexOf('/');
    const stem = slash === -1 ? line : line.slice(0, slash);
    const flags = slash === -1 ? [] : [...line.slice(slash + 1)];
    if (forbidden && flags.includes(forbidden)) continue;
    const meta = { stem, flags, noSuggest: !!noSuggest && flags.includes(noSuggest) };
    onWord(stem, meta);
    const sfxForms = [];
    const pfxRules = [];
    for (const f of flags) {
      const r = rules.get(f);
      if (!r) continue;
      if (r.type === 'SFX') {
        for (const form of applySfx(stem, r)) {
          onWord(form.word, meta);
          sfxForms.push({ ...form, cross: r.cross });
          // one level of continuation classes
          for (const cf of form.cont) {
            const r2 = rules.get(cf);
            if (r2 && r2.type === 'SFX') for (const f2 of applySfx(form.word, r2)) onWord(f2.word, meta);
          }
        }
      } else {
        pfxRules.push(r);
        for (const form of applyPfx(stem, r)) onWord(form.word, meta);
      }
    }
    // cross products
    for (const pr of pfxRules) {
      if (!pr.cross) continue;
      for (const sf of sfxForms) {
        if (!sf.cross) continue;
        for (const form of applyPfx(sf.word, pr)) onWord(form.word, meta);
      }
    }
  }
}
